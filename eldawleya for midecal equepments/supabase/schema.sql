create type quote_status as enum ('New', 'Contacted', 'Quotation Sent', 'Negotiating', 'Completed');

create table categories (
  id bigint generated by default as identity primary key,
  name_ar text not null,
  name_en text not null,
  icon text not null default '•'
);

create table products (
  id bigint generated by default as identity primary key,
  name_ar text not null,
  name_en text not null,
  category_id bigint references categories(id) on delete set null,
  manufacturer text,
  model text,
  description text,
  specs jsonb not null default '[]'::jsonb,
  image_url text,
  datasheet_url text,
  availability text not null default 'متوفر حسب الطلب',
  created_at timestamptz not null default now()
);

create table quote_requests (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  clinic_name text not null,
  phone text not null,
  message text,
  status quote_status not null default 'New',
  created_at timestamptz not null default now()
);

create table quote_request_items (
  id bigint generated by default as identity primary key,
  quote_request_id bigint not null references quote_requests(id) on delete cascade,
  product_id bigint not null references products(id) on delete restrict,
  quantity integer not null check (quantity > 0)
);

alter table categories enable row level security;
alter table products enable row level security;
alter table quote_requests enable row level security;
alter table quote_request_items enable row level security;
create policy "Public can browse categories" on categories for select using (true);
create policy "Public can browse products" on products for select using (true);
create policy "Public can submit quote requests" on quote_requests for insert with check (true);
create policy "Public can submit quote items" on quote_request_items for insert with check (true);
